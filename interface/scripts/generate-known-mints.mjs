// Writes `src/pda/buffer/known_mints.rs`: the mints of the most traded verified
// Solana tokens, whose buffer PDAs the interface derives at compile time so the
// settlement program can skip re-deriving them on-chain.
//
// Ranks Jupiter's verified token list by 24h volume. Jupiter's own `toptraded`
// ranking isn't used because it leaves out base tokens such as SOL and USDC.

import { writeFileSync } from "node:fs";

const COUNT = 63;
const SOURCE = "https://lite-api.jup.ag/tokens/v2/tag?query=verified";
const OUTPUT = new URL("../src/pda/buffer/known_mints.rs", import.meta.url);

const response = await fetch(SOURCE);
if (!response.ok) {
  throw new Error(`${SOURCE} answered ${response.status}`);
}
const tokens = await response.json();

const volume = ({ stats24h }) =>
  (stats24h?.buyVolume ?? 0) + (stats24h?.sellVolume ?? 0);
const ranked = tokens.sort((a, b) => volume(b) - volume(a)).slice(0, COUNT);
if (ranked.length !== COUNT) {
  throw new Error(
    `expected at least ${COUNT} verified tokens, got ${ranked.length}`,
  );
}

// Symbols are free-form text; keep only what reads safely in a line comment.
const label = (symbol) => symbol.replace(/[^\x20-\x7e]/g, "").trim() || "?";
const date = new Date().toISOString().slice(0, 10);
// Aligns the symbol comments the way rustfmt does.
const width = Math.max(...ranked.map(({ id }) => id.length));

writeFileSync(
  OUTPUT,
  `// @generated by \`just generate-known-mints\` on ${date}. Do not edit by hand.

/// The ${COUNT} verified tokens with the highest 24h trading volume on Jupiter,
/// most traded first.
pub(super) const KNOWN_MINTS: [&str; ${COUNT}] = [
${ranked.map(({ id, symbol }) => `    ${`"${id}",`.padEnd(width + 3)} // ${label(symbol)}`).join("\n")}
];
`,
);
